<script setup lang="ts">
/*
 * A Payment Acknowledgement Receipt laid out for an 80mm thermal printer.
 *
 * Read from the receipt's frozen snapshot, as the A4 PDF is, so the two say
 * the same thing. Headed by the issuing centre's own logo — the one the
 * receipt was issued with — or its initials when it has none. Black on white
 * only: a thermal printer has no colour.
 *
 * Emits `ready` once the logo has loaded (or there is none), so a print page
 * does not print before the logo is on it.
 */
import type { PaymentReceiptSummary } from '~/types/bloodRequest'
import { facilityInitials, pesos } from '~/utils/billing'

const props = defineProps<{ receipt: PaymentReceiptSummary }>()
const emit = defineEmits<{ ready: [] }>()

const issuer = computed(() => props.receipt.issuing_facility ?? null)
const initials = computed(() => facilityInitials(issuer.value?.name))
const logoFailed = ref(false)

function onLogoError() {
  logoFailed.value = true
  emit('ready')
}

function when(iso: string | null | undefined): string {
  return iso ? new Date(iso).toLocaleString('en-PH', { dateStyle: 'medium', timeStyle: 'short' }) : '—'
}

onMounted(() => {
  if (!issuer.value?.logo_url) emit('ready')
})
</script>

