      <div v-else class="t-monogram" aria-hidden="true">{{ initials }}</div>
      <strong class="t-centre">{{ issuer?.name || 'Blood centre' }}</strong>
      <span v-if="issuer?.address" class="t-small">{{ issuer.address }}</span>
      <span v-if="issuer?.phone" class="t-small">{{ issuer.phone }}</span>
    </header>

    <div class="t-rule" />

    <p class="t-title">PAYMENT ACKNOWLEDGEMENT RECEIPT</p>
    <p v-if="receipt.voided" class="t-void">VOID — {{ receipt.void_reason }}</p>

    <dl class="t-kv">
      <div><dt>Receipt No.</dt><dd>{{ receipt.receipt_number }}</dd></div>
