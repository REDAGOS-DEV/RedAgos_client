      <div v-if="receipt.request?.reference_number"><dt>Request</dt><dd>{{ receipt.request.reference_number }}</dd></div>
      <div v-if="receipt.statement"><dt>Statement</dt><dd>{{ receipt.statement.document_number }}</dd></div>
      <div v-if="receipt.payer_name"><dt>Received from</dt><dd>{{ receipt.payer_name }}</dd></div>
      <div v-if="receipt.request?.patient_name"><dt>Patient</dt><dd>{{ receipt.request.patient_name }}</dd></div>
    </dl>

    <template v-if="receipt.lines?.length">
      <div class="t-rule t-rule--dashed" />
      <table class="t-lines">
        <tbody>
          <tr v-for="(line, i) in receipt.lines" :key="i">
            <td>
              {{ line.component_name }}
              <span class="t-small">{{ line.quantity }} × {{ pesos(line.unit_price) }}</span>
            </td>
            <td class="t-num">{{ pesos(line.line_total) }}</td>
          </tr>
        </tbody>
      </table>
    </template>

    <div class="t-rule t-rule--dashed" />

    <dl class="t-kv t-totals">
      <div v-if="receipt.statement"><dt>Bill total</dt><dd>{{ pesos(receipt.statement.total_amount) }}</dd></div>
      <div><dt>Balance before</dt><dd>{{ pesos(receipt.balance_before) }}</dd></div>
      <div class="t-big"><dt>AMOUNT RECEIVED</dt><dd>{{ pesos(receipt.amount_paid) }}</dd></div>
      <div><dt>Method</dt><dd>{{ receipt.payment?.method_label || receipt.payment_method_label || '—' }}</dd></div>
      <template v-if="receipt.payment?.amount_tendered">
        <div><dt>Cash tendered</dt><dd>{{ pesos(receipt.payment.amount_tendered) }}</dd></div>
        <div><dt>Change</dt><dd>{{ pesos(receipt.payment.change_given) }}</dd></div>
      </template>
      <div class="t-strong"><dt>Balance after</dt><dd>{{ pesos(Math.max(Number(receipt.balance_after ?? 0), 0)) }}</dd></div>
    </dl>

    <p class="t-note">
      {{ receipt.is_partial ? 'Part payment. The balance above is still due before blood is released.' : 'The bill is settled by this payment.' }}
    </p>

    <div class="t-rule" />

    <dl class="t-kv">
      <div><dt>Cashier</dt><dd>{{ receipt.received_by || 'Payment provider' }}</dd></div>
      <div v-if="receipt.payment?.cash_session_number"><dt>Shift</dt><dd>{{ receipt.payment.cash_session_number }}</dd></div>
      <div v-if="receipt.replaces_receipt_number"><dt>Replaces</dt><dd>{{ receipt.replaces_receipt_number }}</dd></div>
    </dl>

    <p class="t-foot">
      This acknowledges payment received. It is not a BIR official receipt.<br>
      Generated by RedAgos
    </p>
  </article>
